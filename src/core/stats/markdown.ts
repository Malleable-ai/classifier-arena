/**
 * The Markdown beside each generated JSON file (`results/<game>/summary.md`,
 * `results/leaderboard.md`): GitHub tables that say how every number is made. Pure.
 */

const WIN_RATE_NOTE =
  'Win rates are from the first-named player’s side (seat 0’s when a player meets itself), and ' +
  'a draw counts as half a win. ' +
  'Intervals are 95% Wilson score intervals. Only valid matches count.';

const GENERATED = (from: string): string =>
  `Generated by \`pnpm leaderboard\` from ${from}. Don’t edit it by hand.`;

/** Pipes in a cell would split it. */
const cell = (s: string): string => s.replace(/\|/g, '\\|');

function table(head: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]): string => `| ${cells.map(cell).join(' | ')} |`;
  return [line(head), line(head.map(() => '---')), ...rows.map(line)].join('\n');
}

/** A failed run-level check as a GitHub warning block, or nothing. */
function warningBlock(check: RunCheck): string[] {
  const w = runCheckWarning(check);
  return w === null ? [] : ['> [!WARNING]', `> ${w}`, ''];
}

/**
 * summary.md's list of matches whose validity the current rule re-scored, or nothing: those
 * logged invalid and now valid (made invalid only by timeouts or refusals, which no longer
 * count), and those logged valid and now invalid (a stall the log shows).
 */
function rescoredSection(rescored: readonly RescoredMatch[]): string[] {
  if (rescored.length === 0) return [];
  const out: string[] = [];
  const nowValid = rescored.filter((r) => r.valid);
  const nowInvalid = rescored.filter((r) => !r.valid);
  if (nowValid.length > 0) {
    out.push(
      'Re-scored valid under the current validity rule (logged invalid when played, now ' +
        'scored; timeouts no longer count toward validity since 2026-10-16, refusals since ' +
        '2026-10-12):',
      '',
      ...nowValid.map((r) => `- \`${r.id}\``),
      '',
    );
  }
  if (nowInvalid.length > 0) {
    out.push(
      'Re-scored invalid under the current validity rule (logged valid when played, not scored):',
      '',
      ...nowInvalid.map((r) => `- \`${r.id}\``),
      '',
    );
  }
  return out;
}

/**
 * The matches excluded by hand (`results/excluded.json`), each with its reason, under their own
 * heading, or nothing. `level` is the heading's `#`s.
 */
function excludedSection(excluded: readonly ExcludedMatch[], level: string): string[] {
  if (excluded.length === 0) return [];
  return [
    `${level} Excluded by hand`,
    '',
    'Kept but not scored: an infrastructure failure the log can’t show (listed in ' +
      '`results/excluded.json`).',
    '',
    ...excluded.map((e) => `- \`${e.id}\`: ${e.reason}`),
    '',
  ];
}

/** `N invalid` or `N invalid (K excluded by hand)`. */
function invalidCount(matches: { invalid: number; excluded: number }): string {
  return (
    `${String(matches.invalid)} invalid` +
    (matches.excluded > 0 ? ` (${String(matches.excluded)} excluded by hand)` : '')
  );
}

/** summary.md's list of logs of an older game version, or nothing. */
function olderVersionSection(older: readonly OlderVersionMatch[], version: number): string[] {
  if (older.length === 0) return [];
  return [
    `Older version, not scored (this summary scores version ${String(version)}):`,
    '',
    ...older.map((o) => `- \`${o.id}\` (version ${String(o.gameVersion)})`),
    '',
  ];
}

/** summary.md's run-level check section. */
function runCheckSection(check: RunCheck): string[] {
  const limit = formatShare(check.maxMissRate);
  return [
    '## Run-level miss check',
    '',
    `A timeout is the model’s own miss and never makes a match invalid, so the ${limit} miss ` +
      'limit is checked over the whole run: each player’s misses (timeouts and errors) over its ' +
      'decisions in the valid matches.',
    '',
    ...(check.passed
      ? [`Passed: no player missed more than ${limit} of its decisions.`, '']
      : warningBlock(check)),
  ];
}

export function summaryMarkdown(s: GameSummary): string {
  const out: string[] = [
    `# ${s.label}: results`,
    '',
    GENERATED(`the match logs in \`${matchesDir(s.game)}/\``),
    '',
    `Matches: ${String(s.matches.valid)} valid, ${invalidCount(s.matches)}, ` +
      `${String(s.matches.unfinished)} unfinished` +
      (s.matches.olderVersion > 0
        ? `, ${String(s.matches.olderVersion)} of an older version (not scored). `
        : '. ') +
      `Spend over every log: ${formatUsd(s.totalCostUsd)}.` +
      (s.runIds.length === 0
        ? ''
        : s.runIds.length === 1
          ? ` Provider runs carry run id ${s.runIds[0] ?? ''}.`
          : ` Provider runs carry run ids ${s.runIds.join(', ')} (ids from before 2026-10-15 were hashed from the host name, which changed with the network; see ${RUN_ID_DOC}).`),
    '',
  ];
  out.push(...warningBlock(s.runCheck));
  if (s.matches.total === 0) {
    out.push('No matches yet.', '');
  } else {
    out.push(
      '## Pairings',
      '',
      table(
        ['Pairing', 'Valid matches', 'Wins–draws–losses', 'Win rate', '95% interval', 'Invalid'],
        s.pairings.map((p) => [
          `${p.labels[0]} vs ${p.labels[1]}`,
          String(p.matches),
          formatRecord(p),
          p.matches === 0 ? NONE : formatPercent(p.winRate.p),
          p.matches === 0 ? NONE : formatInterval(p.winRate),
          String(p.invalid),
        ]),
      ),
      '',
      WIN_RATE_NOTE,
      '',
      '## Players',
      '',
      table(
        [
          'Player',
          'Kind',
          'Matches',
          'Decisions',
          'Miss rate',
          'Refusal rate',
          'Accuracy',
          'p50 latency',
          'p95 latency',
          'Cost per 1,000 decisions',
        ],
        s.players.map((p) => [
          p.label,
          p.kind,
          String(p.matches),
          String(p.decisions),
          formatPercent(p.decisions === 0 ? null : p.missRate),
          formatPercent(p.decisions === 0 ? null : p.refusalRate),
          s.graded ? formatPercent(p.accuracy) : 'not graded',
          formatMs(p.latencyMs.p50),
          formatMs(p.latencyMs.p95),
          formatUsd(p.costPer1000),
        ]),
      ),
      '',
      'Miss rate is timeouts and transport errors over decisions. Refusal rate is the decisions ' +
        'the model declined to answer: no move is played, and a refusal never makes a match ' +
        'invalid. Latency is over decisions the API answered (`ok` and `dropped`). Accuracy is ' +
        'over answers the game graded. Cost includes each match’s warm-up call.',
      '',
    );
  }
  out.push(...runCheckSection(s.runCheck));
  if (s.invalidMatches.length > 0) {
    out.push('Invalid matches (kept, not scored):', '');
    for (const m of s.invalidMatches) out.push(`- \`${m.id}\`: ${m.reason}`);
    out.push('');
  }
  out.push(...rescoredSection(s.rescored));
  out.push(...excludedSection(s.excluded, '##'));
  out.push(...olderVersionSection(s.olderVersion, s.gameVersion));
  const f = s.featured;
  out.push(
    f === null
      ? 'Featured match: none yet (it is the closest valid head-to-head).'
      : `Featured match: \`${f.id}\` (${featuredResult(s, f)}, the closest valid head-to-head).`,
    '',
  );
  return out.join('\n');
}

/** "Jev wins on the tiebreak (33–33)": the featured match's result, named by short labels. */
function featuredResult(s: GameSummary, f: NonNullable<GameSummary['featured']>): string {
  const name = (player: string): string => {
    const label = s.players.find((p) => p.player === player)?.label ?? player;
    return label.replace(/\s*\([^)]*\)\s*$/, '').trim() || label;
  };
  return formatResult([name(f.players[0]), name(f.players[1])], f.winner, f.scores);
}

function h2hText(h: HeadToHeadCell | null): string {
  if (h === null) return NONE;
  return `${formatPercent(h.winRate.p)} (${formatInterval(h.winRate)}, n=${String(h.matches)})`;
}

export function leaderboardMarkdown(lb: Leaderboard): string {
  const out: string[] = [
    '# Leaderboard',
    '',
    GENERATED('every committed match log, through each game’s `summary.json`'),
    '',
    `**Overall score.** ${lb.formula}`,
    '',
  ];
  if (lb.models.length === 0 || lb.models.every((m) => m.overall === null)) {
    out.push('No head-to-head runs yet: there is no overall score until there are.', '');
  }
  if (lb.models.length > 0) {
    out.push(
      table(
        ['Model', 'Overall', ...lb.games.map((g) => g.label)],
        lb.models.map((m) => [
          m.label,
          formatPercent(m.overall),
          ...m.games.map((c) => h2hText(c.headToHead)),
        ]),
      ),
      '',
      'Each game column is the head-to-head win rate with its 95% interval and match count.',
      '',
    );
  }
  const flagged = lb.games.filter((g) => runCheckWarning(g.runCheck) !== null);
  if (flagged.length > 0) {
    out.push(
      '> [!WARNING]',
      `> ${flagged.map((g) => g.label).join(', ')}: the run-level miss check failed (see below).`,
      '',
    );
  }

  for (const [i, g] of lb.games.entries()) {
    out.push(`## ${g.label}`, '');
    out.push(
      `${String(g.matches.valid)} valid matches (${String(g.matches.headToHead)} head to head), ` +
        `${invalidCount(g.matches)}.` +
        (g.featured === null ? '' : ` Featured: \`${g.featured}\`.`),
      '',
      ...warningBlock(g.runCheck),
      ...excludedSection(g.excluded, '###'),
    );
    const rows = lb.models.filter(
      (m) => (m.games[i]?.decisions ?? 0) > 0 || m.games[i]?.headToHead,
    );
    if (rows.length === 0) {
      out.push('No published runs yet.', '');
      continue;
    }
    out.push(
      table(
        [
          'Model',
          'Head-to-head win rate',
          '95% interval',
          'Matches',
          'Accuracy',
          'Refusal rate',
          'p50 latency',
          'p95 latency',
          'Cost per 1,000 decisions',
        ],
        rows.map((m) => {
          const c = m.games[i];
          const h = c?.headToHead ?? null;
          return [
            m.label,
            h === null ? NONE : formatPercent(h.winRate.p),
            h === null ? NONE : formatInterval(h.winRate),
            h === null ? '0' : String(h.matches),
            g.graded ? formatPercent(c?.accuracy ?? null) : 'not graded',
            formatPercent(c === undefined || c.decisions === 0 ? null : c.refusalRate),
            formatMs(c?.latencyMs.p50 ?? null),
            formatMs(c?.latencyMs.p95 ?? null),
            formatUsd(c?.costPer1000 ?? null),
          ];
        }),
      ),
      '',
    );
  }

  out.push('## Baselines', '');
  if (lb.baselineRecords.length > 0) {
    out.push(
      'Each model against the baselines:',
      '',
      table(
        ['Game', 'Model', 'Opponent', 'Matches', 'Wins–draws–losses', 'Win rate', '95% interval'],
        lb.baselineRecords.map((r) => [
          labelOf(lb, r.game),
          r.label,
          r.opponentLabel,
          String(r.matches),
          formatRecord(r),
          formatPercent(r.winRate.p),
          formatInterval(r.winRate),
        ]),
      ),
      '',
    );
  }
  if (lb.baselines.length === 0) {
    out.push('No baseline matches yet.', '');
  } else {
    out.push(
      'The baselines’ own numbers:',
      '',
      table(
        ['Game', 'Baseline', 'Matches', 'Decisions', 'Accuracy', 'p50 latency', 'p95 latency'],
        lb.baselines.map((b) => {
          const graded = lb.games.find((g) => g.id === b.game)?.graded ?? false;
          return [
            labelOf(lb, b.game),
            b.label,
            String(b.matches),
            String(b.decisions),
            graded ? formatPercent(b.accuracy) : 'not graded',
            formatMs(b.latencyMs.p50),
            formatMs(b.latencyMs.p95),
          ];
        }),
      ),
      '',
      'Baselines answer after a fixed 200 ms delay, so their latency is not a measurement.',
      '',
    );
  }

  out.push('## Notes', '', ...leaderboardNotes(lb).map((n) => `- ${n}`), '');
  return out.join('\n');
}

function labelOf(lb: Leaderboard, game: string): string {
  return lb.games.find((g) => g.id === game)?.label ?? game;
}
